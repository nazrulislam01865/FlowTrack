function nextClientCodePreview() {
        const max = clients.reduce((highest, client) => {
            const match = String(client.code || '').match(/^CL-(\d+)$/i);
            return match ? Math.max(highest, Number(match[1])) : highest;
        }, 0);
        return `CL-${String(max + 1).padStart(3, '0')}`;
    }

