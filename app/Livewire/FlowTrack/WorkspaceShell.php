<?php

namespace App\Livewire\FlowTrack;

use Livewire\Attributes\Locked;
use Livewire\Attributes\On;
use Livewire\Attributes\Renderless;
use Livewire\Component;

class WorkspaceShell extends Component
{
    /**
     * Canonical route-level screen names. Existing IDs are intentionally kept
     * unchanged because the reference UI and its compatibility renderer use
     * them as stable DOM contracts.
     *
     * @var list<string>
     */
    public const SCREENS = [
        'dashboard',
        'mywork',
        'jobs',
        'clients',
        'board',
        'documents',
        'reports',
        'notifications',
        'workflowsetup',
        'taskpacksetup',
        'masterdata',
        'setup',
        'profile',
    ];

    #[Locked]
    public array $screens = self::SCREENS;

    #[Locked]
    public string $activePage = 'dashboard';

    public function mount(): void
    {
        $this->activePage = $this->pageFromPath(request()->path());
    }

    /**
     * Keep the current screen in the session without morphing the renderer's
     * DOM. This creates a Livewire lifecycle boundary while preserving the
     * exact HTML generated by the existing, proven screen renderers.
     */
    #[On('flowtrack:navigate')]
    #[Renderless]
    public function rememberPage(string $page): void
    {
        if (! in_array($page, self::SCREENS, true) && ! str_starts_with($page, 'record-')) {
            return;
        }

        session()->put('flowtrack.livewire.active_page', $page);
    }

    public function render()
    {
        return view('livewire.flow-track.workspace-shell');
    }

    private function pageFromPath(string $path): string
    {
        $segments = array_values(array_filter(explode('/', trim($path, '/'))));

        if (($segments[0] ?? null) !== 'flowtrack' || ($segments[1] ?? null) !== 'view') {
            return 'dashboard';
        }

        $page = $segments[2] ?? 'dashboard';

        return match ($page) {
            'tasks' => 'mywork',
            'workflows' => 'workflowsetup',
            'task-packs' => 'taskpacksetup',
            default => in_array($page, self::SCREENS, true) ? $page : 'dashboard',
        };
    }
}
