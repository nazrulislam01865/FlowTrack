<?php

namespace App\Http\Requests\FlowTrack;

use App\Modules\OrderFlow\Business\Enums\MasterDataType;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class StoreMasterRecordRequest extends FormRequest
{
    public function authorize(): bool
    {
        return $this->route('record')
            ? ($this->user()?->hasFlowAction('masterdata', 'edit_all') ?? false)
            : ($this->user()?->hasFlowAction('masterdata', 'create') ?? false);
    }

    public function rules(): array
    {
        $workspaceId = $this->user()->currentWorkspaceId();

        return [
            'type' => ['required', Rule::enum(MasterDataType::class)],
            'parent_id' => [
                'nullable',
                'integer',
                Rule::exists('master_records', 'id')->where(fn ($query) => $query
                    ->where('workspace_id', $workspaceId)
                    ->where('type', MasterDataType::ProductCategory->value)
                    ->where('status', 'active')
                    ->whereNull('deleted_at')),
            ],
            // Codes are generated by the server and are intentionally not accepted from forms.
            'name' => ['required', 'string', 'max:255'],
            'description' => ['nullable', 'string', 'max:3000'],
            'metadata' => ['nullable', 'array'],
            'status' => ['required', Rule::in(['active', 'inactive'])],
            'sort_order' => ['nullable', 'integer', 'min:0'],
        ];
    }
}
